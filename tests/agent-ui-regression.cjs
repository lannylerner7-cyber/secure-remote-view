// Static UI-contract guards, not Windows interaction tests.
const assert = require("node:assert/strict");
const fs = require("node:fs");
const path = require("node:path");
const workspaceDir = path.resolve(__dirname, "../agent/src");
const dir = fs.existsSync(workspaceDir) ? workspaceDir : path.resolve(__dirname, "../agent/src");
const read = (file) => fs.readFileSync(path.join(dir, file), "utf8");
for (const removed of ["AuthorizationPrompt.cs", "SplashWindow.xaml.cs", "AgentTray.cs"]) {
  assert.equal(fs.existsSync(path.join(dir, removed)), false, `${removed} must not ship`);
}
const prompt = read("PairingPrompt.cs");
assert.equal((prompt.match(/new Window\b/g) || []).length, 1, "one onboarding window");
assert.equal((prompt.match(/new TextBox\b/g) || []).length, 1, "only the pairing-code input");
assert.doesNotMatch(prompt, /new CheckBox\b|new RadioButton\b|new Expander\b|NotifyIcon/);
assert.match(prompt, /One-time pairing code/);
assert.match(prompt, /BrandAccent/);
assert.match(prompt, /PrimaryButton/);
assert.match(prompt, /Pair and connect/);
assert.match(prompt, /string\.IsNullOrWhiteSpace\(input\.Text\)/);
assert.match(prompt, /InspectPairingAsync/);
assert.match(prompt, /Organization: \{offer\.Organization\}/);
assert.match(prompt, /offer\.Capabilities\.Control/);
assert.match(prompt, /offer\.Capabilities\.Clipboard/);
assert.match(prompt, /offer\.Capabilities\.Files/);
assert.match(prompt, /offer\.Capabilities\.Recording/);
assert.match(prompt, /offer\.Mode == "unattended"/);
assert.match(prompt, /details\.Visibility = Visibility\.Visible/);
assert.match(prompt, /attempt\.Offer\.ExpiresAt <= DateTimeOffset\.UtcNow/);
assert.match(prompt, /CompletePairingAsync/);
assert.match(prompt, /token\.ThrowIfCancellationRequested\(\)/);
assert.match(prompt, /window\.Closed.*if \(!paired\) cancellation\.Cancel/);
assert.match(prompt, /IsCancel = true/);
assert.match(prompt, /bool startWithWindows = false/);
assert.match(prompt, /startWithWindows && companionsAvailable/);
assert.match(prompt, /ConnectLive\.exe \/disable/);
assert.ok(prompt.indexOf("await api.CompletePairingAsync") <
  prompt.indexOf("LocalAccessState.CompleteForegroundReauthorization"));
const app = read("App.xaml.cs");
assert.doesNotMatch(app, /SplashWindow|AuthorizationPrompt|ReviewAuthorization|RecordAuthorizationAsync|AgentTray|_tray|NotifyIcon/);
assert.match(app, /forcePair \|\| !HasUsablePairing\(api\)/);
assert.match(app, /if \(backgroundLaunch\) \{ Shutdown\(\); return; \}/);
assert.match(app, /if \(!await PairingPrompt\.ShowAsync\(api, _cts\.Token, startWithWindows\)\)\s*\{\s*DisableRemoteAccess/);
assert.match(app, /local\.DeviceId == api\.DeviceId && local\.Origin == LocalGrant\.OriginOf\(api\.ApiBaseUrl\)/);
assert.match(app, /!LocalAccessState\.IsDisabled\(\)/);
assert.match(app, /api\.PairingProvider = null/);
assert.ok(app.indexOf("if (!HasUsablePairing(api))") < app.indexOf("new Agent(api"));
assert.match(app, /_agent\?\.StopLocally\(\)/);
assert.match(app, /LocalAccessState\.Disable\(\)/);
assert.match(app, /StartupConsent\.Clear\(\)/);
assert.match(app, /a\.Equals\("\/disable"/);
assert.match(app, /a\.Equals\("--disable"/);
assert.ok(app.indexOf('Log.Info("startup entered') < app.indexOf("var uninstalling"),
  "file logging must initialize before early startup exits");
assert.match(app, /if \(LocalAccessState\.IsDisabled\(\) \|\| InstallationLifecycle\.RemovalRequested\(\)\) DisableRemoteAccess\(\)/);
assert.match(read("App.xaml"), /ShutdownMode="OnExplicitShutdown"/);
const runner = fs.readFileSync(path.join(dir, "../run.ps1"), "utf8");
assert.match(runner, /"build", \(Join-Path/);
assert.match(runner, /ConnectLiveAgent\.csproj/);
assert.match(runner, /ConnectLiveWatch\.csproj/);
assert.match(runner, /ConnectLiveUpdate\.csproj/);
assert.match(runner, /--pair/);
assert.match(runner, /Start-Process/);
assert.match(runner, /if \(\$Disable\)/);
assert.match(runner, /-ArgumentList "\/disable"/);
assert.match(runner, /--start-with-windows/);
assert.match(runner, /\[switch\]\$Logs/);
assert.ok(runner.indexOf("if ($Logs)") < runner.indexOf("Get-Command dotnet"),
  "opening logs must not need the SDK");
assert.match(runner, /Start-Transcript/);
assert.match(runner, /Stop-Transcript/);
assert.match(runner, /RedirectStandardError/);
assert.match(read("Agent.cs"), /System\.IO\.Path\.GetTempPath\(\)/);
assert.match(read("ScreenCapture.cs"), /RefreshUnchangedJpeg/);
assert.match(read("ScreenCapture.cs"), /first JPEG uploaded successfully/);
assert.doesNotMatch(runner, /Invoke-WebRequest|Invoke-RestMethod|&.*build\.ps1|dotnet publish|msiexec|Compress-Archive/i);
console.log("PASS: single-input pairing, no tray/status controls, inline admin-selected access, explicit startup, and local command-line withdrawal (static checks only)");
