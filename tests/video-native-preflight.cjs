const fs = require("node:fs");
const assert = require("node:assert/strict");
// Works from the repository or a complete source-only Agent ZIP.
const root = fs.existsSync("agent/src") ? "agent/" : "agent/";
const read = file => fs.readFileSync(root + file, "utf8");
const app = read("src/App.xaml.cs");
const offline = app.indexOf('a.Equals("--video-preflight"');
assert.ok(offline > 0 && offline < app.indexOf("var backgroundLaunch"));
assert.ok(offline < app.indexOf("InputBlocker.LocalStopRequested"), "Offline diagnostics must not initialize input hooks/watchers");
const block = app.slice(offline, app.indexOf("var backgroundLaunch"));
assert.ok(block.includes("VideoPreflight.LogStartup();") && block.includes("Shutdown();") && block.includes("return;"));
assert.ok(!/ApiClient|PairingPrompt|StartupSelfHeal|StartRecovery/.test(block));
const agent = read("src/Agent.cs").split("public async Task RunAsync")[1];
assert.ok(agent.indexOf("VideoPreflight.LogStartup();") < agent.indexOf("EnrollIfNeededAsync"));
const rtc = read("src/WebRtcSession.cs");
assert.ok(rtc.includes("bool offerH264 = !_h264UnavailableForSession && CodecPolicy.AllowH264;"));
assert.ok(rtc.includes("if (_vp8 != null) offered.Add(new VideoFormat(VideoCodecsEnum.VP8"));
assert.ok(!rtc.includes("Vp8NativeDiagnostics.Inspect"), "Native inventory must not gate H.264");
assert.ok(rtc.includes("actual encoder initialization/frames still required"));
const h264 = read("src/HwH264Encoder.cs");
assert.ok(!h264.includes("staying on VP8"), "Failed H.264 initialization must not assert an untested fallback");
assert.ok(h264.includes("VP8 fallback requires its own successful probe"));
const native = read("src/WindowsVp8NativeProbe.cs");
assert.ok(native.includes("LoadLibrarySearchDllLoadDir | LoadLibrarySearchSystem32"));
assert.ok(native.includes('AppContext.GetData("NATIVE_DLL_SEARCH_DIRECTORIES")'));
assert.ok(native.includes("Path.IsPathFullyQualified"));
assert.ok(!/SetDllDirectory|AddDllDirectory|SetDllImportResolver|Process\.Start|WebClient|HttpClient/.test(native));
assert.ok(!/Environment\.GetEnvironmentVariable|Directory\.EnumerateFiles|SearchOption\.AllDirectories/.test(native));
assert.ok(!/File\.Exists\(name\)/.test(native), "API-set contracts are resolved by Windows, not File.Exists");
const project = read("src/ConnectLiveAgent.csproj");
const diagnostics = read("src/Vp8NativeDiagnostics.cs");
const version = project.match(/Include="SIPSorceryMedia\.Encoders" Version="([^"]+)"/)[1];
assert.ok(diagnostics.includes(`PackageVersion = "${version}"`), "Re-audit native package requirements on version changes");
assert.ok(diagnostics.includes("VCRUNTIME140.dll") && !diagnostics.includes("MSVCP140.dll"));
assert.ok(diagnostics.includes("hresult=0x") && diagnostics.includes("native win32="));
assert.ok(!diagnostics.includes("ex.Message"), "Native diagnostic messages must not leak full paths");
console.log("PASS: startup/offline wiring, honest codec offers, restricted loader and package-version contracts");
